using System.Linq;
using Microsoft.CodeAnalysis;

namespace McpIt.Generator.Tests;

// McpIt.Generated.McpItToolCatalog: one McpToolDescriptor per generated tool, derived from the
// same EndpointModels as the tools themselves (controller, method-group, MapGroup and lambda).
public class ToolCatalogTests
{
    private const string GenericStub = """

        namespace Microsoft.AspNetCore.Builder
        {
            public interface IEndpointRouteBuilder { }
            public static class MinimalApiStubExtensions
            {
                public static void MapGet<THandler>(this IEndpointRouteBuilder b, string p, THandler h) { }
                public static void MapPost<THandler>(this IEndpointRouteBuilder b, string p, THandler h) { }
                public static void MapDelete<THandler>(this IEndpointRouteBuilder b, string p, THandler h) { }
                public static IEndpointRouteBuilder MapGroup(this IEndpointRouteBuilder b, string prefix) => b;
            }
        }
        """;

    // Delegate-typed stub: the real ASP.NET Core shape, which forces the lambda-from-syntax path.
    private const string DelegateStub = """

        namespace Microsoft.AspNetCore.Builder
        {
            public static class TestWebApp
            {
                public static object MapGet(this object app, string route, System.Delegate handler) => app;
                public static object MapPost(this object app, string route, System.Delegate handler) => app;
            }
        }
        """;

    private static string Catalog(GeneratorResult result)
    {
        var src = result.AllGeneratedSource;
        var start = src.IndexOf("// <auto-generated/>\n#nullable enable\nnamespace McpIt.Generated;", System.StringComparison.Ordinal);
        Assert.True(start >= 0, "McpItToolCatalog was not generated:\n" + src);
        var end = src.IndexOf("\n}\n", start, System.StringComparison.Ordinal);
        return src.Substring(start, end - start + 3);
    }

    private static void AssertCompiles(GeneratorResult result) =>
        Assert.Empty(result.CompilationDiagnostics.Where(d => d.Severity == DiagnosticSeverity.Error));

    [Fact]
    public void Controller_actions_produce_catalog_entries_with_class_category_default()
    {
        var src = """
            using McpIt;
            using Microsoft.AspNetCore.Mvc;
            namespace Demo;

            [Route("api/orders")]
            [McpTool(Category = "orders")]
            public class OrdersController : ControllerBase
            {
                /// <summary>Gets a single order by its identifier.</summary>
                [HttpGet("{id}")]
                [McpTool(Keywords = new[] { "lookup", " find ", "LOOKUP", "" }, Priority = 5)]
                public string GetOrder(int id, string? expand, System.Threading.CancellationToken ct) => "ok";

                /// <summary>Deletes an order permanently from the system.</summary>
                [HttpDelete("{id}")]
                [McpTool(Category = "admin", AllowDestructive = true, Title = "Remove order")]
                public void DeleteOrder(int id) { }
            }
            """;

        var result = GeneratorTestHarness.Run(src);
        AssertCompiles(result);
        var catalog = Catalog(result);

        Assert.Contains("internal static class McpItToolCatalog", catalog);
        Assert.Contains(
            "public static global::System.Collections.Generic.IReadOnlyList<global::McpIt.McpToolDescriptor> Tools { get; } = new global::McpIt.McpToolDescriptor[]",
            catalog);

        // Class-level Category is the default; Keywords are trimmed, de-duplicated (case-insensitive)
        // and blanks dropped; the CancellationToken is not a tool parameter.
        Assert.Contains(
            "new global::McpIt.McpToolDescriptor(\"getOrder\", \"Get Order\", \"Gets a single order by its identifier.\", \"GET\", \"api/orders/{id}\", \"orders\", new string[] { \"lookup\", \"find\" }, 5, new string[] { \"id\", \"expand\" }, true, false),",
            catalog);

        // Action-level Category wins over the class default; explicit Title is used.
        Assert.Contains(
            "new global::McpIt.McpToolDescriptor(\"deleteOrder\", \"Remove order\", \"Deletes an order permanently from the system.\", \"DELETE\", \"api/orders/{id}\", \"admin\", global::System.Array.Empty<string>(), 0, new string[] { \"id\" }, false, true),",
            catalog);
    }

